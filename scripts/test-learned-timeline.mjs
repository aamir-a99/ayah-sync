import assert from 'node:assert/strict';
import { LearnedTimeline } from '../src/timeline/learned.js';

const ayah = (ref) => ({ ref, surah: 1, ayah: Number(ref.split(':')[1]), arabic: 'text', translation: 'meaning' });
const t = new LearnedTimeline('video-a', 100);
assert.equal(t.observe(ayah('1:2'), 10), true);
t.observe(ayah('1:2'), 12);
assert.equal(t.entries.length, 1);
assert.equal(t.entries[0].t0, 10, 'recognition point is not a guessed ayah start');
assert.equal(t.entries[0].t1, 12.75);
t.breakRun();
t.observe(ayah('1:7'), 40);
assert.equal(t.entries.length, 2);
assert.ok(t.entries[0].t1 < 40, 'seeking never fills an unheard gap');
t.breakRun();
t.observe(ayah('1:2'), 11);
assert.equal(t.entries.length, 2, 'revisiting a known interval does not duplicate markers');
t.breakRun();
t.observe(ayah('1:2'), 70);
assert.equal(t.entries.length, 3, 'a repeated ayah at a different time has its own marker');
assert.equal(t.observe(ayah('1:3'), Infinity), false);
assert.equal(t.observe(ayah('1:3'), 101), false);
const saved = t.snapshot();
assert.equal(saved.partial, true);
assert.equal(saved.approximate, true);
assert.equal(saved.entries.some((e) => e.w), false, 'no invented word timings');
assert.equal(new LearnedTimeline('video-a', 100, saved).entries.length, 3);
assert.equal(new LearnedTimeline('video-b', 100, saved).entries.length, 0);
assert.equal(new LearnedTimeline('video-a', 120, saved).entries.length, 0);
console.log('Partial timeline observations, gaps, repeated ayahs and video-specific restore checks passed.');
