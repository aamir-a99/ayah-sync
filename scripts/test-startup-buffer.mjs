import assert from 'node:assert/strict';
import { StartupBuffer } from '../src/cpu/startup-buffer.js';
const startup = new StartupBuffer();
assert.equal(startup.update(0, 60, 0, 4).ready, false);
assert.equal(startup.update(0, 60, 0, 11).ready, false);
assert.equal(startup.update(0, 60, 0, 12).ready, true);
assert.equal(startup.update(1, 60, 0, 12).ready, true, 'readiness remains latched during normal playback');
startup.reset();
assert.equal(startup.update(22, 60, 12, 33).ready, false, 'seek needs upcoming audio, not just historical context');
assert.equal(startup.update(22, 60, 12, 34).ready, true);
startup.reset();
assert.equal(startup.update(55, 60, 45, 59).ready, false);
assert.equal(startup.update(55, 60, 45, 60).ready, true, 'near EOF prepare only available audio');
startup.reset();
assert.equal(startup.update(0, 3, 0, 3).ready, true);
startup.reset();
assert.equal(startup.update(0, 60, null, null).ready, false);
assert.equal(startup.update(0, 60, 1, 20).ready, false);
console.log('CPU twelve-second startup gate, seek reset and EOF checks passed.');
